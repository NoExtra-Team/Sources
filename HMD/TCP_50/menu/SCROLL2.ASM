Scrolling:
	movea.l   physique(pc),a0
	add.l	#160*200,a0
	add.l	#160*34+4,a0
	
	lea	buffer,a1
	moveq	#15,d7
.loop:
	roxl	(a1)+
	roxl	152(a0)
	roxl	144(a0)
	roxl	136(a0)
	roxl	128(a0)
	roxl	120(a0)
	roxl	112(a0)
	roxl	104(a0)
	roxl	096(a0)
	roxl	088(a0)
	roxl	080(a0)
	roxl	072(a0)
	roxl	064(a0)
	roxl	056(a0)
	roxl	048(a0)
	roxl	040(a0)
	roxl	032(a0)
	roxl	024(a0)
	roxl	016(a0)
	roxl	008(a0)
	roxl	000(a0)
	lea	160(a0),a0
	dbf	d7,.loop

	addq	#1,sequence
	cmpi	#15,sequence
	ble	nonew
	clr	sequence
.restart:
	move.l	pt_text,a0
	move.b	(a0)+,d0
	tst.b	d0
	bne	nofintxt

	move.l	#text,pt_text
	bra	.restart
	
nofintxt:
	move.l	a0,pt_text
	lea	list_chr,a1
	moveq	#-$1,d1
search:	
	addq	#$1,d1
	cmp.b	(a1)+,d0
	bne.s	search

	lea	char,a0
search0:
	cmpi	#20,d1
	bmi	search1
	lea	640(a0),a0
	subi	#20,d1
	bra.s	search0
search1:
	add	d1,d1	
	lea	0(a0,d1.w),a0

	lea	buffer,a1
	moveq	#15,d0
.recop:
	move	(a0),(a1)+
	lea	40(a0),a0
	dbf	d0,.recop

nonew:
	rts

pt_text:
